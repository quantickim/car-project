import type { EncarPath } from '../api/types';

/**
 * 관심 차종 카탈로그. 제원은 test.txt 를 옮긴 것이고, `encar` 는 엔카 분류 경로다.
 * `badges` 가 있으면 해당 배지(트림)명이 정확히 일치하는 매물만 사용한다.
 */
export interface CatalogCar {
  id: string;
  name: string;
  /** 최고출력(마력). test.txt 에 없으면 국내 제원 기준 값 */
  hp: number;
  zeroTo100: number;
  zeroTo200?: number;
  topSpeed: string;
  suspension: string;
  lengthMm: number;
  widthMm: number;
  description: string;
  /** 관심 연식 (예: [16년식] → 2016) */
  targetYear?: number;
  encar: EncarPath;
  badges?: string[];
  /** 배지 매물이 적을 때 감가 추정에 함께 쓸 유사 트림 키워드 (배지명에 포함되는 문자열) */
  peerKeyword?: string;
  /** 엔카 분류와 정확히 맞지 않을 때의 메모 */
  note?: string;
  custom?: boolean;
}

const audi = (modelGroup: string, model: string, badgeGroup?: string): EncarPath => ({
  carType: 'N',
  manufacturer: '아우디',
  modelGroup,
  model,
  badgeGroup,
});
